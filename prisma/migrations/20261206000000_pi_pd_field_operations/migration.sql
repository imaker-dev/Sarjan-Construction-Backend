-- ── backfill: enable the inheritable set on existing PROJECT/SITE depts ──
-- Departments created before this migration get the same default set that
-- createDepartment now seeds on new PROJECT/SITE departments: every
-- non-sensitive leadership-inheritable operation valid for the scope.
-- Idempotent via the (companyId, departmentId, operationKey) unique key.

INSERT INTO "DepartmentOperation"("id","companyId","departmentId","operationKey")
SELECT gen_random_uuid(), d."companyId", d."id", e."key"
FROM "Department" d
JOIN "OperationCatalogueEntry" e
  ON e."sensitive" = FALSE
 AND e."leadershipInheritable" = TRUE
 AND d."scopeType" = ANY(e."appliesTo")
WHERE d."scopeType" IN ('PROJECT','SITE')
ON CONFLICT ("companyId","departmentId","operationKey") DO NOTHING;
